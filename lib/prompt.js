/**
 * Builds the initial prompt for starting a session with DSH agent to configure a cron task.
 * @param {string} userText 
 * @returns {string}
 */
export function buildAgentCronPrompt(userText) {
  const text = (userText || '').trim();
  return `Пользователь хочет настроить запланированную задачу (cron) через DSH Cron.
Исходный запрос пользователя:
"${text}"

ВАЖНЕЙШИЕ ПРАВИЛА ДЛЯ АГЕНТА:
1. СТРОГИЙ ЗАПРЕТ НА СПЕШКУ:
   КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО вызывать инструмент \`cron_schedule_task\` в первом же ответе!
   Ты НЕ имеешь права создавать задачу, пока не задашь пользователю уточняющие вопросы и не получишь его подтверждение.

2. ЧТО ТЫ ОБЯЗАН УТОЧНИТЬ В ПЕРВОМ ОТВЕТЕ:
   - Тип задачи (LLM или NO-LLM?):
     * LLM-крон: агент запускается по расписанию с языковой моделью, анализирует вывод, делает выводы, парсит неструктурированный текст (расходует токены).
     * NO-LLM крон (скрипт/bash): периодический запуск shell-команды или скрипта (curl, git check, ping, проверка системных служб) БЕЗ участия LLM. Не расходует токены, сообщает только при ненулевом коде возврата или ошибке.
     Спроси пользователя, какой вариант предпочтительнее для его задачи (или аргументированно предложи подходящий).
   - Выбор модели (если выбран LLM-крон):
     * Предложи экономичную и быструю модель (например, \`deepseek/deepseek-v4-flash\` или \`Qwen/Qwen3.8-Flash\`).
     * Спроси, подходит ли эта модель или пользователь хочет использовать другую подключенную модель.
   - Точное расписание (schedule):
     * Предложи конкретное выражение cron (например, "0 */6 * * *" для 4 раз в день или "0 9 * * 1-5" по будням) и понятное текстовое пояснение.
     * Уточни, устраивает ли такое расписание.
   - Silent Rule (Правило тишины / Уведомления):
     * По умолчанию для регулярных проверок действует Silent Rule: если всё в порядке / нет обновлений / сервис работает штатно — агент молчит или возвращает пустой ответ, чтобы не спамить. Оповещение отправляется ТОЛЬКО при обнаружении изменений, обновлений или проблем.
     * Уточни, нужно ли применять Silent Rule или присылать отчёт при каждом запуске.

3. СТРУКТУРА ПЕРВОГО ОТВЕТА:
   - Кратко подтверди суть задачи.
   - Сформулируй проект карточки задачи:
     • Тип: [LLM / NO-LLM]
     • Расписание: [cron-выражение и понятное описание]
     • Модель: [если LLM — предлагаемая модель]
     • Логика проверки и Silent Rule: [кратко]
   - Задай недостающие вопросы (LLM/NO-LLM, модель, расписание, порог алерта).
   - Попроси пользователя подтвердить или скорректировать параметры перед созданием.

4. СОЗДАНИЕ ЗАДАЧИ:
   Только ПОСЛЕ ТОГО, как пользователь ответит и подтвердит параметры, вызови инструмент \`cron_schedule_task\`, передав:
   - title: понятное название задачи
   - schedule: согласованное cron-выражение
   - prompt: финальная подробная инструкция для агента (с обязательным Silent Rule) ИЛИ shell-команда для NO-LLM
   - type: "llm" или "script"
   - provider и model: согласованный провайдер и модель (если type="llm")
   - delivery: "isolated"`;
}
