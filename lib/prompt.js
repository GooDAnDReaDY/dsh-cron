/**
 * Builds the initial prompt for starting a session with DSH agent to configure a cron task.
 * @param {string} userText 
 * @returns {string}
 */
export function buildAgentCronPrompt(userText) {
  const text = (userText || '').trim();
  return `Пользователь хочет настроить запланированную задачу (cron) через DSH Cron.
Исходный запрос пользователя:
"${text}"

ВАЖНЕЙШИЕ ПРАВИЛА ДЛЯ АГЕНТА:
1. СТРОГИЙ ЗАПРЕТ НА СПЕШКУ:
   КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО вызывать инструмент \`cron_schedule_task\` в первом же ответе!
   Ты НЕ имеешь права создавать задачу, пока не задашь пользователю уточняющие вопросы и не получишь его подтверждение.

2. ПЕРВЫЙ ВОПРОС: LLM vs NO-LLM Shell (КРИТИЧЕСКИ ВАЖНО):
   - Оцени характер задачи:
     * Если задача ТРИВИАЛЬНАЯ (проверка RSS/Atom фида, проверка кода ответа HTTP, curl/ping/git check, мониторинг файла или службы) — ТЫ ОБЯЗАН РЕКОМЕНДОВАТЬ NO-LLM Shell (type: "script")!
       Поясни пользователю: "Для этой задачи языковая модель избыточна — простой bash-скрипт с curl/jq отработает за миллисекунды, надежно и не потратит ни единого токена. Рекомендую оформить как NO-LLM Shell-скрипт."
     * Если задача требует СЕМАНТИЧЕСКОГО АНАЛИЗА (обобщение писем, генерация отчета из неструктурированного текста, принятие смысловых решений) — предложи LLM (type: "llm").
   - Спроси пользователя, согласен ли он с предложенным типом задачи.

3. ЧТО ТЫ ОБЯЗАН УТОЧНИТЬ:
   - Если выбран NO-LLM Shell:
     * Предложи готовый shell-скрипт или команду для выполнения.
     * Уточни, подходит ли логика скрипта.
   - Если выбран LLM:
     * Предложи экономичную модель (например, \`deepseek/deepseek-v4-flash\` или \`Qwen/Qwen3.8-Flash\`).
     * Спроси, подходит ли эта модель.
   - Точное расписание (schedule):
     * Предложи конкретное выражение cron (например, "0 */6 * * *" для 4 раз в день или "0 9 * * 1-5" по будням) и понятное текстовое пояснение.
   - Silent Rule (Правило тишины / Уведомления):
     * Для проверок и мониторингов действует жесткое Silent Rule: если новых событий/изменений нет — ПОЛНАЯ ТИШИНА, никаких сообщений в чат/Telegram не отправляется вообще (exit 0 в скрипте или пустой ответ). Оповещение уходит ТОЛЬКО при обнаружении новинок или сбое.
     * Подтверди пользователю, что правило тишины будет включено.

4. СТРУКТУРА ПЕРВОГО ОТВЕТА:
   - Кратко подтверди суть задачи.
   - Сформулируй проект карточки:
     • Тип: [NO-LLM Shell (рекомендуется) / LLM]
     • Расписание: [cron-выражение и понятное описание]
     • Реализация / Скрипт / Модель: [код скрипта или предлагаемая модель]
     • Silent Rule: [только при наличии изменений / сбое]
   - Задай недостающие вопросы и попроси подтвердить создание задачи.

5. СОЗДАНИЕ ЗАДАЧИ:
   Только ПОСЛЕ ТОГО, как пользователь ответит и подтвердит параметры, вызови инструмент \`cron_schedule_task\`, передав:
   - title: понятное название задачи
   - schedule: согласованное cron-выражение
   - prompt: финальная shell-команда/путь к скрипту (для type="script") ИЛИ подробная инструкция с Silent Rule (для type="llm")
   - type: "script" или "llm"
   - provider и model: согласованный провайдер и модель (только если type="llm")
   - delivery: "isolated"`;
}
