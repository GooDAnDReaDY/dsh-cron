test('updater: parseSemver parses core and prereleases', () => {
  assert.deepEqual(parseSemver('0.2.16'), { core: [0, 2, 16], prerelease: [] });
  assert.deepEqual(parseSemver('v1.0.0-rc.1'), { core: [1, 0, 0], prerelease: ['rc', '1'] });
  assert.deepEqual(parseSemver('2.3.4-beta.2+build.123'), { core: [2, 3, 4], prerelease: ['beta', '2'] });
  assert.equal(parseSemver('invalid-version'), undefined);
});

test('updater: isNewerVersion handles versions and prereleases (#147)', () => {
  assert.equal(isNewerVersion('0.2.15', '0.2.16'), true);
  assert.equal(isNewerVersion('0.2.16', '0.2.15'), false);
  assert.equal(isNewerVersion('0.2.16', '0.2.16'), false);
  // Prerelease comparisons
  assert.equal(isNewerVersion('0.2.16-rc.1', '0.2.16'), true, 'final release is newer than prerelease');
  assert.equal(isNewerVersion('0.2.16', '0.2.16-rc.1'), false);
  assert.equal(isNewerVersion('0.2.16-alpha.1', '0.2.16-beta.1'), true);
  assert.equal(isNewerVersion('0.2.16-beta.1', '0.2.16-beta.2'), true);
});

