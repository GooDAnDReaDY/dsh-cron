test('updater: registerPluginUpdater registers GET and POST handlers and rejects cross-origin', async () => {
  let registeredRoute = null;
  const mockWebServer = {
    register: (route) => {
      registeredRoute = route;
      return () => { registeredRoute = null; };
    }
  };
  const mockCtx = {
    webServer: mockWebServer,
    logger: { warn: () => {} }
  };

  const unregister = registerPluginUpdater(mockCtx, {
    endpoint: '/api/dsh-cron/update',
    packageName: '@goodandready/dsh-cron',
    manifestUrl: new URL('../package.json', import.meta.url),
  });

  assert.ok(registeredRoute, 'route must be registered');
  assert.equal(registeredRoute.path, '/api/dsh-cron/update');

  // Test GET status
  let resStatus = 0;
  let resHeaders = {};
  let resBody = '';
  const mockRes = {
    writeHead: (status, headers) => { resStatus = status; resHeaders = headers; },
    end: (body) => { resBody = body; }
  };

  await registeredRoute.handler({ method: 'GET' }, mockRes);
  assert.equal(resStatus, 200);
  const statusData = JSON.parse(resBody);
  assert.equal(statusData.packageName, '@goodandready/dsh-cron');
  assert.ok(statusData.currentVersion);

  // Test POST rejects cross-origin request
  let postStatus = 0;
  let postBody = '';
  const mockPostRes = {
    writeHead: (status, headers) => { postStatus = status; },
    end: (body) => { postBody = body; }
  };

  // Cross-origin request (origin header from external site)
  await registeredRoute.handler({
    method: 'POST',
    headers: { origin: 'http://malicious.example.com', host: '127.0.0.1:3080' }
  }, mockPostRes);

  assert.equal(postStatus, 403, 'cross-origin POST must be rejected with 403');

  unregister();
  assert.equal(registeredRoute, null, 'unregister clears route');
});

test('hygiene: applySilentRule skips non-supported task types (#155)', async () => {
  // llm tasks do not produce command shell output, so silent rule is ignored
  const llmTask = {
    type: 'llm',
    silentRule: 'stay silent if ok'
  };
  assert.equal(supportsSilentRule(llmTask), false);
  const res = await applySilentRule({
    task: llmTask,
    runInfo: { status: 'success' },
    ask: async () => assert.fail('ask should not be called for unsupported task type')
  });
  assert.equal(res.skipped, false);
  assert.equal(res.note, 'task type does not support silent rule');
});
